import me.weishu.kernelsu.ui.component.material.expressiveTopAppBarColors

@Composable
fun AboutScreenMaterial(state: AboutUiState, actions: AboutScreenActions) {
    ExpressiveScaffold(
        topBar = {
            LargeFlexibleTopAppBar(
                title = { Text(state.title) },
                navigationIcon = { TopBarBackButton(onClick = actions.onBack) },
                colors = expressiveTopAppBarColors(),
            )
        },
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
                .verticalScroll(rememberScrollState())
                .padding(horizontal = 24.dp, vertical = 36.dp),
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.spacedBy(16.dp),
        ) {
            Image(
                painter = painterResource(R.drawable.ghost_su_logo),
                contentDescription = state.appName,
                modifier = Modifier.size(100.dp),
            )
            Text(state.appName, style = MaterialTheme.typography.headlineLarge, fontWeight = FontWeight.Bold)
            Text(
                stringResource(R.string.ghostsu_about_description),
                style = MaterialTheme.typography.bodyMedium,
                textAlign = TextAlign.Center,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
            Spacer(Modifier.height(12.dp))
            state.links.forEach { link ->
                Button(
                    onClick = { actions.onOpenLink(link.url) },
                    modifier = Modifier.fillMaxWidth(),
                ) { Text(link.fullText) }
            }
            Text(
                stringResource(R.string.ghostsu_about_licenses),
                style = MaterialTheme.typography.bodySmall,
                textAlign = TextAlign.Center,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
        }
    }
}
